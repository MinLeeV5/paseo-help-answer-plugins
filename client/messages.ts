export function resolveUiLocale(language: UiLanguage, paseoLocale: string): UiLocale {
  if (language !== "auto") return language;
  return /^zh(?:[-_]|$)/i.test(paseoLocale) ? "zh-CN" : "en";
}

export function translator(locale: UiLocale) {
  const resource = locale === "zh-CN" ? chinese : english;
  return (key: MessageKey, values: Record<string, string | number> = {}): string =>
    resource[key].replace(/\{\{(\w+)\}\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

const errorKeys: Record<GenerationErrorCode, MessageKey> = {
  timeout: "errorTimeout", invalidModel: "errorInvalidModel", noModel: "errorNoModel",
  emptyResponse: "errorEmptyResponse", invalidResponse: "errorInvalidResponse",
  incomplete: "errorIncomplete", failed: "errorGeneration", settings: "errorSettings", connection: "errorConnection",
};
export function generationErrorText(batch: Pick<SuggestionBatch, "error" | "errorCode">, locale: UiLocale): string | null {
  return batch.errorCode ? translator(locale)(errorKeys[batch.errorCode]) : batch.error;
}
